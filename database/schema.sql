-- MySQL Database Schema for Online E-commerce Website
-- Target Database: ecommerce_db

CREATE DATABASE IF NOT EXISTS `ecommerce_db` DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE `ecommerce_db`;

-- 1. DANHMUC (Category)
CREATE TABLE IF NOT EXISTS `DANHMUC` (
  `MaDM` INT AUTO_INCREMENT PRIMARY KEY,
  `TenDM` VARCHAR(255) NOT NULL,
  `MoTa` TEXT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 2. SANPHAM (Product)
CREATE TABLE IF NOT EXISTS `SANPHAM` (
  `MaSP` INT AUTO_INCREMENT PRIMARY KEY,
  `TenSP` VARCHAR(255) NOT NULL,
  `GiaBan` DECIMAL(12, 2) NOT NULL,
  `AnhMinhHoa` VARCHAR(500),
  `MoTa` TEXT,
  `ThongSo` TEXT, -- JSON or key-value text representing specifications
  `SoLuongTon` INT NOT NULL DEFAULT 0,
  `TrangThai` VARCHAR(50) NOT NULL DEFAULT 'Đang bán', -- 'Đang bán', 'Ngừng bán'
  `MaDM` INT,
  FOREIGN KEY (`MaDM`) REFERENCES `DANHMUC` (`MaDM`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 3. HINHANH (Product Images)
CREATE TABLE IF NOT EXISTS `HINHANH` (
  `MaAnh` INT AUTO_INCREMENT PRIMARY KEY,
  `DuongDan` VARCHAR(500) NOT NULL,
  `KichThuoc` VARCHAR(50), -- e.g., '1024x768', '500KB'
  `MaSP` INT NOT NULL,
  FOREIGN KEY (`MaSP`) REFERENCES `SANPHAM` (`MaSP`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 4. NGUOIDUNG/KHACHHANG (Users)
CREATE TABLE IF NOT EXISTS `NGUOIDUNG` (
  `MaKH` INT AUTO_INCREMENT PRIMARY KEY,
  `TaiKhoan` VARCHAR(100) NOT NULL UNIQUE,
  `MatKhau` VARCHAR(255) NOT NULL,
  `TenKH` VARCHAR(255) NOT NULL,
  `SDT` VARCHAR(20),
  `Email` VARCHAR(100) NOT NULL UNIQUE,
  `VaiTro` VARCHAR(50) NOT NULL DEFAULT 'Customer', -- 'Customer', 'Admin'
  `TrangThai` VARCHAR(50) NOT NULL DEFAULT 'Hoạt động' -- 'Hoạt động', 'Bị khóa'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 5. GIOHANG (Cart)
CREATE TABLE IF NOT EXISTS `GIOHANG` (
  `MaGioHang` INT AUTO_INCREMENT PRIMARY KEY,
  `MaKH` INT NOT NULL UNIQUE,
  FOREIGN KEY (`MaKH`) REFERENCES `NGUOIDUNG` (`MaKH`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 6. CHITIETGIOHANG (Cart Item Details)
CREATE TABLE IF NOT EXISTS `CHITIETGIOHANG` (
  `GIOHANGMaGioHang` INT NOT NULL,
  `SANPHAMMaSP` INT NOT NULL,
  `SoLuong` INT NOT NULL DEFAULT 1,
  PRIMARY KEY (`GIOHANGMaGioHang`, `SANPHAMMaSP`),
  FOREIGN KEY (`GIOHANGMaGioHang`) REFERENCES `GIOHANG` (`MaGioHang`) ON DELETE CASCADE,
  FOREIGN KEY (`SANPHAMMaSP`) REFERENCES `SANPHAM` (`MaSP`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 7. DONHANG (Orders)
CREATE TABLE IF NOT EXISTS `DONHANG` (
  `MaDonHang` INT AUTO_INCREMENT PRIMARY KEY,
  `NgayDatHang` DATE NOT NULL,
  `ThoiGianDatHang` DATETIME NOT NULL,
  `TongTien` DECIMAL(12, 2) NOT NULL,
  `TrangThai` VARCHAR(50) NOT NULL DEFAULT 'Chờ xử lý', -- 'Chờ xử lý', 'Đã xác nhận', 'Đang giao', 'Đã giao', 'Đã hủy'
  `DiaChiGiaoHang` VARCHAR(500) NOT NULL,
  `SDTNhanHang` VARCHAR(20) NOT NULL,
  `GhiChu` TEXT,
  `MaKH` INT,
  FOREIGN KEY (`MaKH`) REFERENCES `NGUOIDUNG` (`MaKH`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 8. CHITIETDONHANG (Order Item Details)
CREATE TABLE IF NOT EXISTS `CHITIETDONHANG` (
  `MaDonHang` INT NOT NULL,
  `MaSP` INT NOT NULL,
  `DongGia` DECIMAL(12, 2) NOT NULL,
  `SoLuong` INT NOT NULL,
  `ThanhTien` DECIMAL(12, 2) NOT NULL,
  PRIMARY KEY (`MaDonHang`, `MaSP`),
  FOREIGN KEY (`MaDonHang`) REFERENCES `DONHANG` (`MaDonHang`) ON DELETE CASCADE,
  FOREIGN KEY (`MaSP`) REFERENCES `SANPHAM` (`MaSP`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
